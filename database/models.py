class AgentDecision(Base):
    """Agent decisions and reasoning (audit trail)."""
    __tablename__ = "agent_decisions"
    
    id = Column(Integer, primary_key=True, index=True)
    agent_name = Column(SQLEnum(AgentName), nullable=False, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id"), nullable=True, index=True)
    decision_type = Column(String(100), nullable=False)  # e.g., "BUY_RECOMMENDATION", "SQL_QUERY"
    reasoning = Column(Text)  # LLM reasoning/explanation
    confidence_score = Column(Float)  # 0-100
    input_data = Column(Text)  # JSON string of input data
    output_data = Column(Text)  # JSON string of output data
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False, index=True)
    
    # Relationships
    stock = relationship("Stock")


class Order(Base):
    """Orders with approval workflow."""
    __tablename__ = "orders"
    
    id = Column(Integer, primary_key=True, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id"), nullable=False, index=True)
    order_type = Column(SQLEnum(OrderType), nullable=False)
    quantity = Column(Integer, nullable=False)
    price = Column(Float)  # Limit price (if applicable)
    order_status = Column(SQLEnum(OrderStatus), default=OrderStatus.PENDING_APPROVAL, nullable=False, index=True)
    
    # Trade plan details
    entry_price = Column(Float)
    stop_loss = Column(Float)
    target_price = Column(Float)
    confidence_score = Column(Float)  # From strategy agent
    
    # Timestamps
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False, index=True)
    approved_at = Column(DateTime, nullable=True)
    rejected_at = Column(DateTime, nullable=True)
    executed_at = Column(DateTime, nullable=True)
    
    # Execution details
    executed_price = Column(Float)
    execution_message = Column(Text)
    broker_order_id = Column(String(100), nullable=True)  # Shoonya/Upstox order ID
    
    # Relationships
    stock = relationship("Stock", back_populates="orders")
    trades = relationship("Trade", back_populates="order")


class Trade(Base):
    """Executed trades."""
    __tablename__ = "trades"
    
    id = Column(Integer, primary_key=True, index=True)
    order_id = Column(Integer, ForeignKey("orders.id"), nullable=True, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id"), nullable=False, index=True)
    buy_sell = Column(SQLEnum(OrderType), nullable=False)
    quantity = Column(Integer, nullable=False)
    entry_price = Column(Float, nullable=False)
    exit_price = Column(Float, nullable=True)
    stop_loss = Column(Float)
    target = Column(Float)
    pnl = Column(Float, default=0.0)
    pnl_percent = Column(Float, default=0.0)
    status = Column(SQLEnum(TradeStatus), default=TradeStatus.OPEN, nullable=False, index=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False, index=True)
    executed_at = Column(DateTime, nullable=True)
    closed_at = Column(DateTime, nullable=True)
    
    # Relationships
    stock = relationship("Stock", back_populates="trades")
    order = relationship("Order", back_populates="trades")


