"""SQLAlchemy database models."""
from sqlalchemy import (
    Column, Integer, String, Float, DateTime, Boolean, Text,
    ForeignKey, Enum as SQLEnum, Date, Time, UniqueConstraint
)
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import relationship
from datetime import datetime
from config.constants import (
    OrderStatus, OrderType, TradeStatus, SignalType,
    AgentName, Exchange
)

Base = declarative_base()


class Stock(Base):
    """Stock master table."""
    __tablename__ = "stocks"
    
    id = Column(Integer, primary_key=True, index=True)
    symbol = Column(String(50), unique=True, nullable=False, index=True)
    name = Column(String(200), nullable=False)
    exchange = Column(SQLEnum(Exchange), nullable=False, default=Exchange.NSE)
    sector = Column(String(100), nullable=True)
    market_cap = Column(Float, nullable=True)
    is_active = Column(Boolean, default=True, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    # Relationships
    market_data_daily = relationship("MarketDataDaily", back_populates="stock")
    market_data_intraday = relationship("MarketDataIntraday", back_populates="stock")
    screening_signals = relationship("ScreeningSignal", back_populates="stock")
    trades = relationship("Trade", back_populates="stock")
    orders = relationship("Order", back_populates="stock")
    portfolio = relationship("Portfolio", back_populates="stock")
    news_articles = relationship("NewsArticle", back_populates="stock")
    sentiment_scores = relationship("SentimentScore", back_populates="stock")


class MarketDataDaily(Base):
    """Daily market data with 29 technical indicators (2 years history)."""
    __tablename__ = "market_data_daily"
    
    id = Column(Integer, primary_key=True, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id"), nullable=False, index=True)
    date = Column(Date, nullable=False, index=True)
    
    # OHLCV
    open = Column(Float, nullable=False)
    high = Column(Float, nullable=False)
    low = Column(Float, nullable=False)
    close = Column(Float, nullable=False)
    volume = Column(Integer, nullable=False)
    
    # Technical Indicators (29 indicators)
    rsi = Column(Float)
    macd = Column(Float)
    macd_signal = Column(Float)
    macd_histogram = Column(Float)
    bollinger_upper = Column(Float)
    bollinger_lower = Column(Float)
    bollinger_middle = Column(Float)
    sma_20 = Column(Float)
    sma_50 = Column(Float)
    sma_200 = Column(Float)
    ema_12 = Column(Float)
    ema_26 = Column(Float)
    ema_20 = Column(Float)
    ema_50 = Column(Float)
    adx = Column(Float)
    adx_positive = Column(Float)
    adx_negative = Column(Float)
    stochastic_k = Column(Float)
    stochastic_d = Column(Float)
    williams_r = Column(Float)
    cci = Column(Float)
    atr = Column(Float)
    obv = Column(Float)
    mfi = Column(Float)  # Money Flow Index
    volume_sma = Column(Float)
    price_change = Column(Float)
    price_change_percent = Column(Float)
    high_low_range = Column(Float)
    high_low_range_percent = Column(Float)
    volume_ratio = Column(Float)
    momentum = Column(Float)
    roc = Column(Float)  # Rate of Change
    
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    
    # Relationships
    stock = relationship("Stock", back_populates="market_data_daily")
    
    __table_args__ = (
        UniqueConstraint('stock_id', 'date', name='uq_market_data_daily_stock_date'),
        {"sqlite_autoincrement": True},
    )


