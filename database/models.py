class NewsArticle(Base):
    """News articles from various sources (30-day retention)."""
    __tablename__ = "news_articles"
    
    id = Column(Integer, primary_key=True, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id"), nullable=True, index=True)  # NULL for macro/news
    source = Column(String(100), nullable=False)  # 'economic_times', 'moneycontrol', etc.
    title = Column(String(500), nullable=False)
    content = Column(Text, nullable=False)  # Full article text
    url = Column(String(500), unique=True, nullable=False)
    published_date = Column(DateTime, nullable=False)
    category = Column(String(50), nullable=True)  # 'stock_specific', 'sector', 'macro', 'government', 'international'
    relevance_score = Column(Float, nullable=True)  # 0-1 (how relevant to trading)
    is_macro = Column(Boolean, default=False, nullable=False)
    macro_category = Column(String(100), nullable=True)  # 'rbi_rate_cut', 'gdp_growth', etc.
    affected_sectors = Column(Text, nullable=True)  # JSON array
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    
    # Relationships
    stock = relationship("Stock", back_populates="news_articles")
    macro_sentiment_mappings = relationship("MacroStockSentiment", back_populates="news_article")


class SentimentScore(Base):
    """Daily aggregated sentiment scores per stock."""
    __tablename__ = "sentiment_scores"
    
    id = Column(Integer, primary_key=True, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id"), nullable=True, index=True)  # NULL for market-wide sentiment
    date = Column(Date, nullable=False, index=True)
    
    # Sentiment metrics
    overall_sentiment = Column(Float, nullable=False)  # -1 (bearish) to +1 (bullish)
    confidence = Column(Float, nullable=False)  # 0-1 (how confident in sentiment)
    article_count = Column(Integer, default=0, nullable=False)  # Number of articles analyzed
    
    # Sentiment breakdown
    positive_count = Column(Integer, default=0, nullable=False)
    negative_count = Column(Integer, default=0, nullable=False)
    neutral_count = Column(Integer, default=0, nullable=False)
    
    # Category-specific sentiment
    stock_specific_sentiment = Column(Float, nullable=True)  # News about this stock
    sector_sentiment = Column(Float, nullable=True)  # News about sector
    macro_sentiment = Column(Float, nullable=True)  # Macro economic news
    government_sentiment = Column(Float, nullable=True)  # Government policy news
    international_sentiment = Column(Float, nullable=True)  # International trade news
    
    # Metadata
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    
    # Relationships
    stock = relationship("Stock", back_populates="sentiment_scores")
    
    __table_args__ = (
        UniqueConstraint('stock_id', 'date', name='uq_sentiment_scores_stock_date'),
        {"sqlite_autoincrement": True},
    )


class MacroStockSentiment(Base):
    """Mapping of macro news to individual stock sentiment."""
    __tablename__ = "macro_stock_sentiment"
    
    id = Column(Integer, primary_key=True, index=True)
    news_article_id = Column(Integer, ForeignKey("news_articles.id"), nullable=False, index=True)
    stock_id = Column(Integer, ForeignKey("stocks.id"), nullable=False, index=True)
    macro_sentiment = Column(Float, nullable=False)  # Original macro sentiment
    sector_impact = Column(Float, nullable=False)  # Sector-level impact
    stock_sentiment = Column(Float, nullable=False)  # Final stock-specific sentiment
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    
    # Relationships
    news_article = relationship("NewsArticle", back_populates="macro_sentiment_mappings")
    stock = relationship("Stock")


